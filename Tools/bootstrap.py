import unreal
unreal.EditorAssetLibrary.make_directory('/Game/Maps')
unreal.EditorAssetLibrary.make_directory('/Game/Art')
tools=unreal.AssetToolsHelpers.get_asset_tools()
m=unreal.load_asset('/Game/Art/M_Palette')
if not m:
 m=tools.create_asset('M_Palette','/Game/Art',unreal.Material,unreal.MaterialFactoryNew())
 c=unreal.MaterialEditingLibrary.create_material_expression(m,unreal.MaterialExpressionVectorParameter,0,0)
 c.set_editor_property('parameter_name','Color')
 c.set_editor_property('default_value',unreal.LinearColor(0.9,0.83,0.72,1))
 unreal.MaterialEditingLibrary.connect_material_property(c,'',unreal.MaterialProperty.MP_BASE_COLOR)
 r=unreal.MaterialEditingLibrary.create_material_expression(m,unreal.MaterialExpressionConstant,0,150)
 r.set_editor_property('r',0.68)
 unreal.MaterialEditingLibrary.connect_material_property(r,'',unreal.MaterialProperty.MP_ROUGHNESS)
 unreal.MaterialEditingLibrary.recompile_material(m)
 unreal.EditorAssetLibrary.save_loaded_asset(m)
levels=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
if not unreal.EditorAssetLibrary.does_asset_exist('/Game/Maps/LivingRoom'):
 levels.new_level('/Game/Maps/LivingRoom')
 post=unreal.get_editor_subsystem(unreal.EditorActorSubsystem).spawn_actor_from_class(unreal.PostProcessVolume,unreal.Vector(0,0,0))
 post.set_editor_property('unbound',True)
 settings=post.get_editor_property('settings')
 settings.set_editor_property('override_auto_exposure_method',True)
 settings.set_editor_property('auto_exposure_method',unreal.AutoExposureMethod.AEM_MANUAL)
 settings.set_editor_property('override_auto_exposure_bias',True)
 settings.set_editor_property('auto_exposure_bias',7.0)
 post.set_editor_property('settings',settings)
 levels.save_current_level()
unreal.log('BAD_CAT_BOOTSTRAP_OK')
